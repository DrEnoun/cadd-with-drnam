// Turns a PDB file (e.g. 3LN1: COX-2 with celecoxib) into the compact JSON the 3D viewer uses.
// Usage: node tools/prepare-pdb.mjs path/to/3LN1.pdb  ->  writes data/docking/cox2.json and data/docking/3LN1_chainA.pdb
// The structure is centred on the ligand. Chain A, the ligand CEL 682, and the haem are kept.
import { readFileSync, writeFileSync } from 'node:fs';
const [, , file = '3LN1.pdb', CH = 'A', LIG = 'CEL'] = process.argv;
const lines = readFileSync(file, 'utf8').split('\n');
const num = (l, a, b) => parseFloat(l.slice(a, b));
const parse = l => ({ rec: l.slice(0, 6).trim(), name: l.slice(12, 16).trim(), alt: l[16], res: l.slice(17, 20).trim(), ch: l[21], seq: +l.slice(22, 26), x: num(l, 30, 38), y: num(l, 38, 46), z: num(l, 46, 54), el: (l.slice(76, 78).trim() || l.slice(12, 16).trim()[0]).toUpperCase() });
const all = lines.filter(l => l.startsWith('ATOM  ') || l.startsWith('HETATM')).map(parse).filter(a => a.ch === CH && (a.alt === ' ' || a.alt === 'A'));
const prot = all.filter(a => a.rec === 'ATOM'), lig = all.filter(a => a.res === LIG), hem = all.filter(a => a.res === 'HEM');
const D = (a, b) => Math.hypot(a.x - b.x, a.y - b.y, a.z - b.z);
const c0 = lig.reduce((s, a) => [s[0] + a.x / lig.length, s[1] + a.y / lig.length, s[2] + a.z / lig.length], [0, 0, 0]);
const P = a => [+(a.x - c0[0]).toFixed(2), +(a.y - c0[1]).toFixed(2), +(a.z - c0[2]).toFixed(2)];
const COV = { C: .76, N: .71, O: .66, S: 1.05, F: .57, FE: 1.3 };
const bondsOf = atoms => { const b = []; for (let i = 0; i < atoms.length; i++) for (let j = i + 1; j < atoms.length; j++) { const lim = (COV[atoms[i].el] ?? .8) + (COV[atoms[j].el] ?? .8) + .4; if (D(atoms[i], atoms[j]) < lim && atoms[i].el !== 'H' && atoms[j].el !== 'H') b.push([i, j]); } return b; };

// secondary structure from HELIX / SHEET records
const ss = new Map();
for (const l of lines) {
  if (l.startsWith('HELIX ') && l[19] === CH) for (let s = +l.slice(21, 25); s <= +l.slice(33, 37); s++) ss.set(s, 1);
  if (l.startsWith('SHEET ') && l[21] === CH) for (let s = +l.slice(22, 26); s <= +l.slice(33, 37); s++) if (!ss.has(s)) ss.set(s, 2);
}
const ca = prot.filter(a => a.name === 'CA').map(a => [...P(a), ss.get(a.seq) ?? 0, a.seq]);
const lit = seq => seq + (seq < 100 ? 15 : 14); // usual COX-2 literature numbering (PDB file numbers are 14-15 lower)

// pocket residues: any atom within 4.5 Å of the ligand
const byRes = new Map();
for (const a of prot) { const k = a.seq; (byRes.get(k) ?? byRes.set(k, []).get(k)).push(a); }
const pocket = [];
for (const [seq, atoms] of byRes) {
  if (Math.min(...atoms.flatMap(a => lig.map(l => D(a, l)))) > 4.5) continue;
  pocket.push({ name: atoms[0].res, seq, label: `${atoms[0].res}${lit(seq)}`, atoms: atoms.map(a => [a.el, ...P(a), a.name]), bonds: bondsOf(atoms) });
}
// every heavy protein atom near the ligand, for clash checks
const near = prot.filter(a => lig.some(l => D(a, l) < 9)).map(a => [a.el, ...P(a), `${a.res}${lit(a.seq)}:${a.name}`]);
const out = {
  _about: 'Prepared from PDB 3LN1 (COX-2 with celecoxib), chain A. Coordinates in Å, centred on the ligand. Generated by tools/prepare-pdb.mjs.',
  pdb: '3LN1', chain: CH, ligandName: 'celecoxib', numbering: 'Residue labels use the usual COX-2 literature numbering (PDB file number + 14, or +15 below residue 100).',
  ligand: { atoms: lig.map(a => [a.el, ...P(a), a.name]), bonds: bondsOf(lig) },
  heme: { atoms: hem.map(a => [a.el, ...P(a)]), bonds: bondsOf(hem) },
  ca, pocket, near,
};
writeFileSync('data/docking/cox2.json', JSON.stringify(out));
const keep = l => (l.startsWith('ATOM  ') || l.startsWith('HETATM')) && l[21] === CH && (l.slice(17, 20) === LIG || l.slice(17, 20) === 'HEM' || l.startsWith('ATOM  '));
writeFileSync('data/docking/3LN1_chainA.pdb', [...lines.filter(l => /^(HEADER|TITLE|COMPND|SOURCE|JRNL|REMARK   2 )/.test(l)), ...lines.filter(keep), 'END', ''].join('\n'));
console.log('ligand', lig.length, 'heme', hem.length, 'CA', ca.length, 'pocket', pocket.map(p => p.label).join(' '), 'near', near.length);
